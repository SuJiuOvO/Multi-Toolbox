#!/usr/bin/env python3
"""Synchronize application version from pubspec.yaml to lib/constants/app_version.dart."""

import os
import re
import sys
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent
PUBSPEC_PATH = ROOT_DIR / "pubspec.yaml"
TARGET_PATH = ROOT_DIR / "lib" / "constants" / "app_version.dart"


def get_pubspec_version() -> str:
    if not PUBSPEC_PATH.is_file():
        raise FileNotFoundError(f"pubspec.yaml not found at {PUBSPEC_PATH}")
    content = PUBSPEC_PATH.read_text(encoding="utf-8")
    match = re.search(r"^version:\s*([0-9]+\.[0-9]+\.[0-9]+)", content, re.MULTILINE)
    if not match:
        raise ValueError(f"Could not parse semver from {PUBSPEC_PATH}")
    return match.group(1)


def update_version_file(check_only: bool = False) -> bool:
    version = get_pubspec_version()
    expected_content = (
        "// Generated by tools/update_version.py. Do not edit manually.\n"
        "// Source: pubspec.yaml\n"
        f"const String kAppVersion = '{version}';\n"
    )

    if TARGET_PATH.is_file():
        current_content = TARGET_PATH.read_text(encoding="utf-8")
        if current_content == expected_content:
            print(f"[OK] {TARGET_PATH.relative_to(ROOT_DIR)} is up to date (v{version}).")
            return True
        elif check_only:
            print(f"[ERROR] {TARGET_PATH.relative_to(ROOT_DIR)} is outdated! Expected v{version}.")
            return False

    if check_only:
        print(f"[ERROR] {TARGET_PATH.relative_to(ROOT_DIR)} does not exist! Expected v{version}.")
        return False

    TARGET_PATH.parent.mkdir(parents=True, exist_ok=True)
    TARGET_PATH.write_text(expected_content, encoding="utf-8", newline="\n")
    print(f"[SUCCESS] Updated {TARGET_PATH.relative_to(ROOT_DIR)} -> v{version}")
    return True


if __name__ == "__main__":
    check = "--check" in sys.argv
    success = update_version_file(check_only=check)
    sys.exit(0 if success else 1)
